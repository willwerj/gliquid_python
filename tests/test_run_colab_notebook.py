    assert summary["http_requests"] == [
        {"method": "GET", "host": "api.x.org", "path": "/q?a=1", "cells": [6]}
    ]
    assert summary["hosts"] == [
        {"host": "api.x.org", "cells": [6]},
        {"host": "startup.org", "cells": []},
    ]


