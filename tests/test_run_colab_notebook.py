def test_freeze_changes_reports_colab_distributions_only():
    colab = rcn.parse_freeze("numpy==2.1.3\npandas==2.2.3\nipython==7.34.0\nplotly==5.24.1\n")
    before = rcn.parse_freeze("numpy==2.1.3\npandas==2.2.3\nipython==7.34.0\nextra==1.0\n")
    after = rcn.parse_freeze("numpy==2.3.0\npandas==2.2.2\nextra==2.0\nplotly==5.24.1\nscipy==1\n")
    changes = {c["name"]: c for c in rcn.freeze_changes(before, after, colab)}
