"""Pure helpers of ``scripts/run_colab_notebook.py``: no docker, no network, no git.

The script is loaded by file path from the repository root (the first ancestor named
``gliquid_python``); the module skips where ``scripts/`` does not ship.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

from ._mpds_builders import code_cells, shipped_notebooks


def _load_script():
    for parent in Path(__file__).resolve().parents:
        if parent.name == "gliquid_python":
            path = parent / "scripts" / "run_colab_notebook.py"
            if not path.is_file():
                return None
            spec = importlib.util.spec_from_file_location("run_colab_notebook", path)
            module = importlib.util.module_from_spec(spec)
            sys.modules[spec.name] = module
            spec.loader.exec_module(module)
            return module
    return None


rcn = _load_script()

