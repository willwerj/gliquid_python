def test_summarize_cells_statuses_errors_and_stderr():
    notebook = {
        "cells": [
            {"cell_type": "markdown", "source": "# title"},
            {
                "cell_type": "code",
                "source": "import gliquid",
                "outputs": [
                    {
                        "output_type": "stream",
                        "name": "stderr",
                        "text": "a.py:1: UserWarning: careful\n",
                    }
                ],
            },
            {
                "cell_type": "code",
                "source": ["bl = f()\n", "bl.go()"],
                "outputs": [
                    {
                        "output_type": "error",
                        "ename": "KeyError",
                        "evalue": "'Cu-Mg'",
                        "traceback": [
                            "\x1b[0;31mTraceback\x1b[0m",
                            "\x1b[0;31mKeyError\x1b[0m: 'Cu-Mg'",
                        ],
                    }
                ],
            },
            {"cell_type": "code", "source": "later()", "outputs": []},
            {"cell_type": "code", "source": "  ", "outputs": []},
        ]
    }
    cells = rcn.summarize_cells(notebook, [1, 2], {"1": 0.5, 2: 1.25})
    assert [(c["index"], c["status"]) for c in cells] == [
        (1, "ok"),
        (2, "error"),
        (3, "not-run"),
        (4, "empty"),
    ]
    assert cells[0]["elapsed"] == 0.5
    assert cells[0]["warnings"] == ["a.py:1: UserWarning: careful"]
    assert cells[1]["error"] == {
        "ename": "KeyError",
        "evalue": "'Cu-Mg'",
        "last_line": "KeyError: 'Cu-Mg'",
    }
    assert cells[1]["first_line"] == "bl = f()"
    assert rcn.deduplicate_warnings(cells + [dict(cells[0], index=7)]) == [
        {"text": "a.py:1: UserWarning: careful", "cells": [1, 7]}
    ]


def test_summarize_audit_maps_sequence_numbers_to_cells():
    records = [
        {"seq": 1, "event": "cache-exists", "key": "k1", "location": "/c/A-B.json", "result": True},
        {
            "seq": 2,
            "event": "cache-exists",
            "key": "k2",
            "location": "/c/C-D.json",
            "result": False,
        },
        {
            "seq": 3,
            "event": "cache-exists",
            "key": "k2",
            "location": "/c/C-D.json",
            "result": False,
        },
        {"seq": 3, "event": "cache-write", "key": "k2", "location": "/c/C-D.json"},
        {"seq": 3, "event": "http", "method": "GET", "host": "api.x.org", "path": "/q?a=1"},
        {"seq": 3, "event": "dns", "host": "api.x.org"},
        {"seq": 0, "event": "dns", "host": "startup.org"},
    ]
    summary = rcn.summarize_audit(records, [2, 4, 6])
    assert summary["cache_misses"] == [{"location": "/c/C-D.json", "key": "k2", "cells": [4, 6]}]
