def test_rewrite_pip_line_adds_find_links_only_for_a_built_pin():
    built = {"0.3.1.dev5+g1a2b3c4"}
    line, notes = rcn.rewrite_pip_line("!pip install -q gliquid[ml]==0.3.1.dev5+g1a2b3c4", built)
    assert line == "!pip install -q gliquid[ml]==0.3.1.dev5+g1a2b3c4 --find-links /wheels"
    assert "local wheel" in notes[0]

    released, notes = rcn.rewrite_pip_line("!pip install gliquid[ml]==0.3.0  # PyPI", built)
    assert released == "!pip install gliquid[ml]==0.3.0  # PyPI"
    assert "PyPI" in notes[0]

    commented, _ = rcn.rewrite_pip_line("!pip install gliquid==0.3.1.dev5+g1a2b3c4  # pin", built)
    assert commented == "!pip install gliquid==0.3.1.dev5+g1a2b3c4 --find-links /wheels  # pin"


